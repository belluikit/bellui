//go:build ignore

// gen_emoji writes emoji_presentation.go from Unicode's emoji-data.txt, at the
// Unicode version the Go standard library's unicode tables use.
//
//	go run gen_emoji.go [emoji-data.txt]
//
// With no argument it downloads the file for unicode.Version.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	src, name := open()
	defer src.Close()

	type rng struct{ lo, hi rune }
	var ranges []rng
	sc := bufio.NewScanner(src)
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		cps, prop, ok := strings.Cut(line, ";")
		if !ok || strings.TrimSpace(prop) != "Emoji_Presentation" {
			continue
		}
		lo, hi, found := strings.Cut(strings.TrimSpace(cps), "..")
		if !found {
			hi = lo
		}
		ranges = append(ranges, rng{parse(lo), parse(hi)})
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(ranges) == 0 {
		log.Fatalf("%s: no Emoji_Presentation entries", name)
	}

	sort.Slice(ranges, func(i, j int) bool { return ranges[i].lo < ranges[j].lo })
	merged := ranges[:1]
	for _, r := range ranges[1:] {
		last := &merged[len(merged)-1]
		if r.lo <= last.hi+1 {
			last.hi = max(last.hi, r.hi)
			continue
		}
		merged = append(merged, r)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_emoji.go from %s; DO NOT EDIT.\n\n", name)
	b.WriteString("package painter\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&b, "// emojiPresentationVersion is the Unicode version of emojiPresentation.\n")
	fmt.Fprintf(&b, "const emojiPresentationVersion = %q\n\n", unicode.Version)
	fmt.Fprintf(&b, "// emojiPresentation holds the runes whose default presentation is emoji\n")
	fmt.Fprintf(&b, "// (Emoji_Presentation=Yes, Unicode %s, UTS #51).\n", unicode.Version)
	b.WriteString("var emojiPresentation = &unicode.RangeTable{\n\tR16: []unicode.Range16{\n")
	latin := 0
	for _, r := range merged {
		if r.hi <= 0xFFFF {
			fmt.Fprintf(&b, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", r.lo, r.hi)
			if r.hi <= unicode.MaxLatin1 {
				latin++
			}
		}
	}
	b.WriteString("\t},\n\tR32: []unicode.Range32{\n")
	for _, r := range merged {
		if r.hi > 0xFFFF {
			fmt.Fprintf(&b, "\t\t{Lo: 0x%X, Hi: 0x%X, Stride: 1},\n", r.lo, r.hi)
		}
	}
	fmt.Fprintf(&b, "\t},\n\tLatinOffset: %d,\n}\n", latin)

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("emoji_presentation.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func open() (io.ReadCloser, string) {
	if len(os.Args) > 1 {
		f, err := os.Open(os.Args[1])
		if err != nil {
			log.Fatal(err)
		}
		return f, "emoji-data.txt " + unicode.Version
	}
	url := "https://www.unicode.org/Public/" + unicode.Version + "/ucd/emoji/emoji-data.txt"
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	return resp.Body, "emoji-data.txt " + unicode.Version
}

func parse(s string) rune {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return rune(v)
}
