func writeIOSFile(t *testing.T, dir, name, content string) {
	t.Helper()
	p := filepath.Join(dir, iosExtrasDir, name)
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
	require.NoError(t, os.WriteFile(p, []byte(content), 0o644))
}

// plutilLint checks data with Apple's own parser when it is installed, the
// same parser Xcode reads the file with.
func plutilLint(t *testing.T, data []byte) {
	t.Helper()
	if _, err := exec.LookPath("plutil"); err != nil {
		t.Log("plutil not installed; Apple-parser check skipped")
		return
	}
	p := filepath.Join(t.TempDir(), "check.plist")
	require.NoError(t, os.WriteFile(p, data, 0o644))
	out, err := exec.Command("plutil", "-lint", p).CombinedOutput()
	require.NoError(t, err, "%s\n%s", out, data)
	t.Logf("plutil: %s", bytes.TrimSpace(out))
}

func TestPlistRoundTrip(t *testing.T) {
	v, err := parsePlist([]byte(allTypesFragment))
	require.NoError(t, err)
	out := encodePlist(v)
	again, err := parsePlist(out)
	require.NoError(t, err)
	assert.Equal(t, v, again)
	assert.Equal(t, out, encodePlist(again), "encoding is deterministic")
	assert.Equal(t, "aGVsbG8=", v.get("MyData").Text)
	assert.Equal(t, "a & b", v.get("NSAppTransportSecurity").get("Note").Text)
	assert.Contains(t, string(out), "<string>a &amp; b</string>")
	plutilLint(t, out)
}

func TestPlistRejects(t *testing.T) {
	for name, doc := range map[string]string{
		"not a dict":  `<plist><array/></plist>`,
		"dup key":     `<plist><dict><key>A</key><true/><key>A</key><false/></dict></plist>`,
		"no value":    `<plist><dict><key>A</key></dict></plist>`,
		"unknown":     `<plist><dict><key>A</key><bogus/></dict></plist>`,
		"loose value": `<plist><dict><string>x</string></dict></plist>`,
		"not plist":   `<dict/>`,
	} {
		_, err := parsePlist([]byte(doc))
		assert.Error(t, err, name)
	}
}

func generatedInfoPlist(t *testing.T, d infoplistTmplData) []byte {
	t.Helper()
	buf := &bytes.Buffer{}
	require.NoError(t, infoplistTmpl.Execute(buf, d))
	return buf.Bytes()
}

func TestMergeInfoPlistFragment(t *testing.T) {
	data := infoplistTmplData{BundleID: "com.example.t", Name: "T", Version: "1.0", Build: 1}
	gen := generatedInfoPlist(t, data)
	frag, err := parsePlist([]byte(allTypesFragment))
	require.NoError(t, err)

	out, err := mergeInfoPlist(gen, frag, data)
	require.NoError(t, err)
	plutilLint(t, out)
	merged, err := parsePlist(out)
	require.NoError(t, err)

	// New keys keep their type.
	modes := merged.get("UIBackgroundModes")
	require.NotNil(t, modes)
	assert.Equal(t, "array", modes.Kind)
	assert.Equal(t, "audio", modes.Items[0].Text)
	assert.Equal(t, "false", merged.get("ITSAppUsesNonExemptEncryption").Kind)
	assert.Equal(t, "integer", merged.get("MyCount").Kind)

	// A generated key is replaced whole, in its generated position.
	orient := merged.get("UISupportedInterfaceOrientations")
	assert.Len(t, orient.Items, 1)
	base, err := parsePlist(gen)
	require.NoError(t, err)
	idx := func(v *plistValue, k string) int {
		for i, key := range v.Keys {
			if key == k {
				return i
			}
		}
		return -1
	}
	assert.Equal(t, idx(base, "UISupportedInterfaceOrientations"), idx(merged, "UISupportedInterfaceOrientations"))
	// Appended keys follow the generated ones, in fragment order.
	assert.Equal(t, len(base.Keys), idx(merged, "UIBackgroundModes"))
	assert.Equal(t, "com.example.t", merged.get("CFBundleIdentifier").Text)

	// No fragment: the generated bytes pass through untouched.
	same, err := mergeInfoPlist(gen, nil, data)
	require.NoError(t, err)
	assert.Equal(t, gen, same)
}

func TestMergeInfoPlistConflicts(t *testing.T) {
	data := infoplistTmplData{
		BundleID: "com.example.t", Name: "T", Version: "1.0", Build: 1,
		UsageDescriptions: sortedPlistEntries(map[string]string{"NSCameraUsageDescription": "Scan."}),
		URLSchemes:        []string{"t"},
		MimeTypes:         []string{"text/plain"},
		Credit:            "credit",
	}
	gen := generatedInfoPlist(t, data)
	for key, want := range map[string]string{
		"CFBundleIdentifier":         "--app-id",
		"CFBundleExecutable":         "managed by the packager",
		"CFBundleName":               "Details.Name",
		"CFBundleShortVersionString": "Details.Version",
		"CFBundleVersion":            "Details.Build",
		"NSCameraUsageDescription":   "IOSUsageDescriptions",
		"CFBundleURLTypes":           "URLSchemes",
		"CFBundleDocumentTypes":      "file associations",
		"NSHumanReadableCopyright":   "credit",
	} {
		frag := &plistValue{Kind: "dict"}
		frag.set(key, plistString("x"))
		_, err := mergeInfoPlist(gen, frag, data)
		if assert.Error(t, err, key) {
			assert.Contains(t, err.Error(), key)
			assert.Contains(t, err.Error(), want)
		}
	}

	// Without the manifest values, the derived keys are the fragment's to set.
	plain := infoplistTmplData{BundleID: "com.example.t", Name: "T", Version: "1.0", Build: 1}
	frag := &plistValue{Kind: "dict"}
	for _, k := range []string{"NSCameraUsageDescription", "CFBundleURLTypes", "NSHumanReadableCopyright"} {
		frag.set(k, plistString("x"))
	}
	_, err := mergeInfoPlist(generatedInfoPlist(t, plain), frag, plain)
	assert.NoError(t, err)
}

const healthKitFragment = `<plist version="1.0"><dict>
	<key>com.apple.developer.healthkit</key><true/>
	<key>com.apple.developer.healthkit.access</key><array/>
</dict></plist>`

func TestIOSEntitlementsFragment(t *testing.T) {
	none, err := iosEntitlements(t.TempDir(), nil)
	require.NoError(t, err)
	assert.Nil(t, none, "nothing to sign in: no entitlements file")

	dir := t.TempDir()
	writeIOSFile(t, dir, iosEntitlementsFile, healthKitFragment)
	ent, err := iosEntitlements(dir, nil)
	require.NoError(t, err)
	require.NotNil(t, ent)
	assert.Equal(t, []string{"com.apple.developer.healthkit", "com.apple.developer.healthkit.access"}, ent.Keys)

	ent, err = iosEntitlements(dir, []string{"example.com"})
	require.NoError(t, err)
	assert.Equal(t, []string{associatedDomainsKey, "com.apple.developer.healthkit", "com.apple.developer.healthkit.access"}, ent.Keys)
	plutilLint(t, encodePlist(ent))

	writeIOSFile(t, dir, iosEntitlementsFile, `<plist><dict><key>`+associatedDomainsKey+`</key><array/></dict></plist>`)
	_, err = iosEntitlements(dir, []string{"example.com"})
	assert.ErrorContains(t, err, "AssociatedDomains")
	_, err = iosEntitlements(dir, nil)
	assert.NoError(t, err, "the fragment may set the key when the manifest does not")

	writeIOSFile(t, dir, iosEntitlementsFile, `<plist><array/></plist>`)
	_, err = iosEntitlements(dir, nil)
	assert.ErrorContains(t, err, "Entitlements.plist")
}

func TestIOSReleaseEntitlements(t *testing.T) {
	dir := t.TempDir()
	writeIOSFile(t, dir, iosEntitlementsFile, healthKitFragment)
	out, err := IOSReleaseEntitlements(dir, "TEAM", "com.example.t", []string{"example.com"})
	require.NoError(t, err)
	plutilLint(t, out)
	v, err := parsePlist(out)
	require.NoError(t, err)
	assert.Equal(t, []string{"application-identifier", associatedDomainsKey, "com.apple.developer.healthkit", "com.apple.developer.healthkit.access"}, v.Keys)
	assert.Equal(t, "TEAM.com.example.t", v.get("application-identifier").Text)

	writeIOSFile(t, dir, iosEntitlementsFile, `<plist><dict><key>application-identifier</key><string>x</string></dict></plist>`)
	_, err = IOSReleaseEntitlements(dir, "TEAM", "com.example.t", nil)
	assert.Error(t, err)
}

func TestPbxprojEmbedFrameworks(t *testing.T) {
	render := func(embeds []iosEmbed) string {
		buf := &bytes.Buffer{}
		require.NoError(t, projPbxprojTmpl.Execute(buf, projPbxprojTmplData{
			BundleID: "com.example.t", Type: "Auto", TeamID: "TEAM", DeploymentTarget: "15.0", Embeds: embeds,
		}))
		return buf.String()
	}
	without := render(nil)
	assert.NotContains(t, without, "Embed Frameworks")

	with := render(pbxEmbeds([]iosFramework{{Path: "/x/Probe.framework", Dynamic: true}, {Path: "/y/Other.framework", Dynamic: true}}))
	assert.Contains(t, with, "isa = PBXCopyFilesBuildPhase;")
	assert.Contains(t, with, "dstSubfolderSpec = 10;")
	assert.Contains(t, with, `path = "main/Frameworks/Probe.framework";`)
	assert.Equal(t, 2, strings.Count(with, "CodeSignOnCopy"))
	// The phase is wired into the target.
	assert.Contains(t, with, "254BB83C1B1FD08900C56DE9 /* Resources */,\n        B5E1F0C00000000000000000 /* Embed Frameworks */,")
	// Apple's parser reads the project (old-style plist) with the additions.
	plutilLint(t, []byte(with))
}

func TestIOSLinkFlags(t *testing.T) {
	cflags, ldflags := iosLinkFlags([]iosFramework{
		{Name: "Dyn", Path: "/f/ios-arm64/Dyn.framework", Dynamic: true},
		{Name: "Stat", Path: "/f/ios-arm64/Stat.framework"},
		{Name: "libz2.a", Path: "/l/ios-arm64/libz2.a", Headers: "/l/ios-arm64/Headers"},
	})
	assert.Equal(t, []string{"-F/f/ios-arm64", "-F/f/ios-arm64", "-I/l/ios-arm64/Headers"}, cflags)
	assert.Equal(t, []string{
		"-F/f/ios-arm64", "-framework", "Dyn",
		"-F/f/ios-arm64", "-framework", "Stat",
		"/l/ios-arm64/libz2.a",
		"-Wl,-rpath,@executable_path/Frameworks",
	}, ldflags)

	_, ldflags = iosLinkFlags([]iosFramework{{Name: "Stat", Path: "/f/Stat.framework"}})
	assert.NotContains(t, ldflags, "-Wl,-rpath,@executable_path/Frameworks", "static code needs no rpath")

	env := withIOSFlags([]string{"GOOS=ios", "CGO_CFLAGS=-a", "CGO_LDFLAGS=-b"}, []string{"-F/x"}, []string{"-framework", "X"})
	assert.Equal(t, []string{"GOOS=ios", "CGO_CFLAGS=-a -F/x", "CGO_LDFLAGS=-b -framework X"}, env)
}

// TestXCFrameworkSlices builds real xcframeworks with Xcode — a dynamic
// framework and a static library, each with a device and a simulator slice —
// and checks that the packager picks the right slice per build.
func TestXCFrameworkSlices(t *testing.T) {
	if runtime.GOOS != "darwin" {
		t.Skip("needs Xcode")
	}
	if err := exec.Command("xcrun", "--sdk", "iphoneos", "--show-sdk-path").Run(); err != nil {
		t.Skip("needs Xcode with the iOS SDK")
	}
	dir := t.TempDir()
	run := func(args ...string) {
		t.Helper()
		out, err := exec.Command(args[0], args[1:]...).CombinedOutput()
		require.NoError(t, err, "%v\n%s", args, out)
	}
	src := filepath.Join(dir, "probe.c")
	require.NoError(t, os.WriteFile(src, []byte("int probe_answer(void) { return 42; }\n"), 0o644))
	hdr := filepath.Join(dir, "include")
	require.NoError(t, os.MkdirAll(hdr, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(hdr, "probe.h"), []byte("int probe_answer(void);\n"), 0o644))

	type slice struct{ sdk, target, name string }
	slices := []slice{
		{"iphoneos", "arm64-apple-ios15.0", "device"},
		{"iphonesimulator", "arm64-apple-ios15.0-simulator", "sim-arm64"},
		{"iphonesimulator", "x86_64-apple-ios15.0-simulator", "sim-x86_64"},
	}
	for _, s := range slices {
		out := filepath.Join(dir, s.name)
		fw := filepath.Join(out, "Probe.framework")
		require.NoError(t, os.MkdirAll(fw, 0o755))
		run("xcrun", "--sdk", s.sdk, "clang", "-target", s.target, "-dynamiclib", "-install_name",
			"@rpath/Probe.framework/Probe", "-o", filepath.Join(fw, "Probe"), src)
		require.NoError(t, os.WriteFile(filepath.Join(fw, "Info.plist"), []byte(`<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict>
<key>CFBundleExecutable</key><string>Probe</string>
<key>CFBundleIdentifier</key><string>com.example.probe</string>
<key>CFBundlePackageType</key><string>FMWK</string>
<key>CFBundleVersion</key><string>1</string>
<key>CFBundleShortVersionString</key><string>1.0</string>
<key>MinimumOSVersion</key><string>15.0</string>
</dict></plist>`), 0o644))
		obj := filepath.Join(out, "probe.o")
		run("xcrun", "--sdk", s.sdk, "clang", "-target", s.target, "-c", "-o", obj, src)
		run("xcrun", "ar", "rcs", filepath.Join(out, "libprobe.a"), obj)
	}
	// One simulator slice holds both simulator architectures.
	for _, kind := range []string{"Probe.framework/Probe", "libprobe.a"} {
		simDir := filepath.Join(dir, "sim", filepath.Dir(kind))
		require.NoError(t, os.MkdirAll(simDir, 0o755))
		if strings.HasPrefix(kind, "Probe.framework") {
			run("cp", "-R", filepath.Join(dir, "sim-arm64", "Probe.framework"), filepath.Join(dir, "sim"))
		}
		run("xcrun", "lipo", "-create", "-output", filepath.Join(dir, "sim", kind),
			filepath.Join(dir, "sim-arm64", kind), filepath.Join(dir, "sim-x86_64", kind))
	}

	app := t.TempDir()
	fwDir := filepath.Join(app, iosExtrasDir, iosFrameworksDir)
	require.NoError(t, os.MkdirAll(fwDir, 0o755))
	run("xcodebuild", "-create-xcframework",
		"-framework", filepath.Join(dir, "device", "Probe.framework"),
		"-framework", filepath.Join(dir, "sim", "Probe.framework"),
		"-output", filepath.Join(fwDir, "Probe.xcframework"))
	run("xcodebuild", "-create-xcframework",
		"-library", filepath.Join(dir, "device", "libprobe.a"), "-headers", hdr,
		"-library", filepath.Join(dir, "sim", "libprobe.a"), "-headers", hdr,
		"-output", filepath.Join(fwDir, "ProbeStatic.xcframework"))
	t.Log("built Probe.xcframework and ProbeStatic.xcframework with xcodebuild -create-xcframework")

	// Device build.
	perArch, embed, err := resolveIOSFrameworks(app, []string{"arm64"}, false)
	require.NoError(t, err)
	require.Len(t, perArch["arm64"], 2)
	dyn, stat := perArch["arm64"][0], perArch["arm64"][1]
	assert.True(t, dyn.Dynamic)
	assert.Equal(t, "Probe", dyn.Name)
	assert.Equal(t, "ios-arm64", filepath.Base(filepath.Dir(dyn.Path)))
	assert.False(t, stat.Dynamic)
	assert.Equal(t, "libprobe.a", filepath.Base(stat.Path))
	assert.Equal(t, "ios-arm64", filepath.Base(filepath.Dir(stat.Path)))
	assert.FileExists(t, filepath.Join(stat.Headers, "probe.h"))
	require.Len(t, embed, 1)
	assert.Equal(t, dyn.Path, embed[0].Path)

	// Simulator build: both architectures share the fat simulator slice.
	perArch, embed, err = resolveIOSFrameworks(app, []string{"arm64", "amd64"}, true)
	require.NoError(t, err)
	for _, arch := range []string{"arm64", "amd64"} {
		assert.Equal(t, "ios-arm64_x86_64-simulator", filepath.Base(filepath.Dir(perArch[arch][0].Path)), arch)
	}
	require.Len(t, embed, 1)

	// An architecture the xcframework lacks is a clear error.
	_, _, err = resolveIOSFrameworks(app, []string{"arm"}, false)
	assert.ErrorContains(t, err, "no slice for ios armv7")

	// A static library linked through the flags resolves in a real link.
	cflags, ldflags := iosLinkFlags(perArch["arm64"])
	main := filepath.Join(dir, "main.c")
	require.NoError(t, os.WriteFile(main, []byte("#include <probe.h>\n#include <Probe/Probe.h>\nint main(void) { return probe_answer(); }\n"), 0o644))
	require.NoError(t, os.MkdirAll(filepath.Join(perArch["arm64"][0].Path, "Headers"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(perArch["arm64"][0].Path, "Headers", "Probe.h"), []byte("int probe_answer(void);\n"), 0o644))
	args := append([]string{"--sdk", "iphonesimulator", "clang", "-target", "arm64-apple-ios15.0-simulator", "-o", filepath.Join(dir, "a.out")}, cflags...)
	args = append(args, main)
	args = append(args, ldflags...)
	run(append([]string{"xcrun"}, args...)...)
	out, err := exec.Command("otool", "-l", filepath.Join(dir, "a.out")).Output()
	require.NoError(t, err)
	assert.Contains(t, string(out), "@executable_path/Frameworks", "rpath for the embedded framework")
	out, err = exec.Command("otool", "-L", filepath.Join(dir, "a.out")).Output()
	require.NoError(t, err)
	assert.Contains(t, string(out), "@rpath/Probe.framework/Probe")
	t.Log("linked a simulator binary against both slices")
}
