// Genarsc generates stripped down version of android.jar resources used
// for validation of manifest entries.
//
// Requires ANDROID_HOME be set to the path of the Android SDK and the sdk
// platform pinned by binres.SDKPlatform installed (sdkmanager
// "platforms;android-NN"). The pin, not the newest installed platform, is
// what gets packed, so the output is reproducible; the platform is recorded
// in the generated header.
package main

import (
	"fmt"
	"log"
	"os"
	"strconv"

	"github.com/belluikit/bellui/cmd/bellui/internal/mobile/binres"
)

const tmpl = `// Copyright 2016 The Go Authors.  All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by genarsc.go from %s. DO NOT EDIT.

package binres

var arsc = []byte(%s)
`

func main() {
	arsc, err := binres.PackResources()
	if err != nil {
		log.Fatal(err)
	}
	src := fmt.Sprintf(tmpl, binres.SDKPlatform, strconv.Quote(string(arsc)))
	if err := os.WriteFile("arsc.go", []byte(src), 0o644); err != nil {
		log.Fatal(err)
	}
}
