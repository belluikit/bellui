// Command releasecheck walks a tester through validating a release by hand on
// a desktop app, a native mobile app and the web.
//
//	go run ./hack/releasecheck list   [-platform P] [-area A]   # the checklist as Markdown
//	go run ./hack/releasecheck setup  -platform P [-run]        # how to build what the checks use
//	go run ./hack/releasecheck run    -platform P [-area A] [-from ID] [-report FILE]
//
// P is one of desktop, android, ios, web. A is a comma-separated list of areas
// (see -h). The checks themselves are in checks.go. They run against the
// gallery (github.com/belluikit/gallery) built from this checkout, and against
// the companion app in ./app, which shows the behaviours the gallery does not.
//
// run asks for a verdict on each check, writes every answer to the report as
// it goes, and exits 1 if any check failed, so a release is not tagged on a
// report with a failure in it.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"time"
)

var platforms = []string{"desktop", "android", "ios", "web"}

func main() {
	if len(os.Args) < 2 {
		usage()
		os.Exit(2)
	}
	cmd, args := os.Args[1], os.Args[2:]
	fs := flag.NewFlagSet(cmd, flag.ExitOnError)
	platform := fs.String("platform", "", "desktop, android, ios or web")
	areas := fs.String("area", "", "only these areas, comma-separated: "+strings.Join(allAreas(), ","))
	from := fs.String("from", "", "run: start at this check ID")
	report := fs.String("report", "", "run: report file (default release-validation-<version>-<platform>-<date>.md)")
	gallery := fs.String("gallery", "", "setup: the gallery checkout (default ../gallery next to this repository)")
	doRun := fs.Bool("run", false, "setup: run the build steps instead of only printing them")
	_ = fs.Parse(args)

	if *platform != "" && !slices.Contains(platforms, *platform) {
		fatalf("unknown -platform %q: want one of %s", *platform, strings.Join(platforms, ", "))
	}
	selected := filter(checks, *platform, *areas)

	switch cmd {
	case "list":
		writeMarkdown(os.Stdout, selected, *platform)
	case "setup":
		requirePlatform(*platform)
		setup(*platform, *gallery, *doRun)
	case "run":
		requirePlatform(*platform)
		if *report == "" {
			*report = fmt.Sprintf("release-validation-%s-%s-%s.md", version, *platform, time.Now().Format("2006-01-02"))
		}
		os.Exit(runInteractive(selected, *platform, *from, *report))
	default:
		usage()
		os.Exit(2)
	}
}

func usage() {
	fmt.Fprintf(os.Stderr, `releasecheck validates bellui %s by hand.

  go run ./hack/releasecheck list   [-platform P] [-area A]
  go run ./hack/releasecheck setup  -platform P [-gallery DIR] [-run]
  go run ./hack/releasecheck run    -platform P [-area A] [-from ID] [-report FILE]

platforms: %s
areas:     %s
`, version, strings.Join(platforms, ", "), strings.Join(allAreas(), ", "))
}

func requirePlatform(p string) {
	if p == "" {
		fatalf("-platform is required: one of %s", strings.Join(platforms, ", "))
	}
}

func fatalf(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "releasecheck: "+format+"\n", a...)
	os.Exit(2)
}

func allAreas() []string {
	var out []string
	for _, c := range checks {
		if !slices.Contains(out, c.Area) {
			out = append(out, c.Area)
		}
	}
	return out
}

// filter keeps the checks that apply to platform (all when empty) and belong
// to one of areas (all when empty).
func filter(all []check, platform, areas string) []check {
	var want []string
	if areas != "" {
		want = strings.Split(areas, ",")
		for _, a := range want {
			if !slices.Contains(allAreas(), a) {
				fatalf("unknown area %q: want some of %s", a, strings.Join(allAreas(), ", "))
			}
		}
	}
	var out []check
	for _, c := range all {
		if platform != "" && !c.on(platform) {
			continue
		}
		if len(want) > 0 && !slices.Contains(want, c.Area) {
			continue
		}
		out = append(out, c)
	}
	return out
}

// writeMarkdown prints the checklist, special cases marked, for reading or
// printing without the interactive runner.
func writeMarkdown(w io.Writer, cs []check, platform string) {
	scope := "all platforms"
	if platform != "" {
		scope = platform
	}
	fmt.Fprintf(w, "# bellui %s release validation (%s)\n\n", version, scope)
	fmt.Fprintf(w, "Generated by `go run ./hack/releasecheck list`. Prepare the builds with `go run ./hack/releasecheck setup -platform <p>`.\n")
	fmt.Fprintf(w, "Checks marked **SPECIAL** are edge cases or the riskiest changes of this release: do not skip them.\n\n")
	area := ""
	for _, c := range cs {
		if c.Area != area {
			area = c.Area
			fmt.Fprintf(w, "## %s\n\n", areaTitle[area])
		}
		fmt.Fprint(w, c.markdown())
	}
}

// setup prints, or with run executes, the steps that build what the checks
// open: the bellui command and the gallery from this checkout, and the
// companion app.
func setup(platform, gallery string, run bool) {
	repo := repoRoot()
	if gallery == "" {
		gallery = filepath.Join(filepath.Dir(repo), "gallery")
	}
	app := filepath.Join(repo, "hack", "releasecheck", "app")
	var replaces []string
	replaces = append(replaces, "-replace github.com/belluikit/bellui="+repo)
	for _, m := range []string{"charts", "dag", "editor", "mmedia", "tables"} {
		replaces = append(replaces, fmt.Sprintf("-replace github.com/belluikit/bellui/x/%s=%s", m, filepath.Join(repo, "x", m)))
	}

	type step struct {
		what, dir, cmd string
		auto           bool // safe to run with -run on any machine that has the platform's tools
	}
	steps := []step{
		{"Build the bellui command from this checkout (the release's CLI fixes are part of what is tested)", filepath.Join(repo, "cmd", "bellui"), "go install .", true},
		{"Get the gallery (skip if it is already there)", filepath.Dir(gallery), "git clone https://github.com/belluikit/gallery.git " + filepath.Base(gallery), true},
		{"Point the gallery at this checkout instead of a published release", gallery, "go mod edit " + strings.Join(replaces, " ") + " && go mod tidy", true},
	}
	switch platform {
	case "desktop":
		steps = append(
			steps,
			step{"Build the gallery", gallery, "go build -o gallery .", true},
			step{"Build the gallery with the screen-reader bridges (for the a11y checks)", gallery, "go build -tags accessibility -o gallery-a11y .", true},
			step{"Build the companion app, next to the gallery", repo, "go build -o " + filepath.Join(gallery, "releasecheck-app") + " ./hack/releasecheck/app", true},
			step{"Build the companion app with the screen-reader bridges", repo, "go build -tags accessibility -o " + filepath.Join(gallery, "releasecheck-app-a11y") + " ./hack/releasecheck/app", true},
			step{"Run them (Linux/macOS; on Windows run the .exe). Start each again with LANG=... where a check says so", gallery, "./gallery   # and ./releasecheck-app", false},
		)
	case "android":
		steps = append(
			steps,
			step{"Package the gallery (the gallery's own script also repacks and signs the APK; it needs ANDROID_HOME and an NDK)", gallery, "scripts/android-build.sh --install", false},
			step{"Package the companion app with the screen-reader bridges", app, "bellui package -os android/arm64 -tags accessibility && adb install -r Release_Check.apk", false},
			step{"Watch the log while testing; a crash or a Go panic shows here", "", "adb logcat -s GoLog:* AndroidRuntime:E", false},
		)
	case "ios":
		steps = append(
			steps,
			step{"Package the gallery for a device (needs macOS, Xcode and a provisioning profile; -appID names the profile)", gallery, "bellui package -os ios -appID <your.profile.id>", false},
			step{"Package the companion app with the screen-reader bridges", app, "bellui package -os ios -tags accessibility -appID <your.profile.id>", false},
			step{"Install both on the device (Xcode → Devices and Simulators, or ios-deploy)", "", "ios-deploy --bundle <App>.app", false},
		)
	case "web":
		steps = append(
			steps,
			step{"Serve the gallery, then open http://localhost:8080 in Chrome or Edge", gallery, "bellui serve", false},
			step{"Serve the companion app on another port, then open http://localhost:8081", app, "bellui serve --http-port 8081", false},
		)
	}

	fmt.Printf("Setup for %s (bellui %s, checkout %s)\n\n", platform, version, repo)
	for i, s := range steps {
		fmt.Printf("%d. %s\n", i+1, s.what)
		if s.dir != "" {
			fmt.Printf("   cd %s\n", s.dir)
		}
		fmt.Printf("   %s\n\n", s.cmd)
		if !run {
			continue
		}
		if !s.auto {
			fmt.Printf("   (not run: needs your devices or an interactive session)\n\n")
			continue
		}
		if strings.HasPrefix(s.cmd, "git clone") {
			if _, err := os.Stat(gallery); err == nil {
				fmt.Printf("   (skipped: %s exists)\n\n", gallery)
				continue
			}
		}
		c := exec.Command("sh", "-c", s.cmd)
		if runtime.GOOS == "windows" {
			c = exec.Command("cmd", "/C", s.cmd)
		}
		c.Dir, c.Stdout, c.Stderr = s.dir, os.Stdout, os.Stderr
		if err := c.Run(); err != nil {
			fatalf("step %d failed: %v", i+1, err)
		}
		fmt.Printf("   ok\n\n")
	}
	fmt.Printf("Then: go run ./hack/releasecheck run -platform %s\n", platform)
}

// repoRoot is the checkout this command runs from: the directory holding the
// main module's go.mod above the working directory.
func repoRoot() string {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/belluikit/bellui").Output()
	if err != nil {
		fatalf("run this from the bellui checkout: %v", err)
	}
	return strings.TrimSpace(string(out))
}

// runInteractive shows each check, records the tester's verdict in the report
// after every answer, and returns the exit code: 1 when a check failed.
func runInteractive(cs []check, platform, from, reportPath string) int {
	if from != "" {
		i := slices.IndexFunc(cs, func(c check) bool { return c.ID == from })
		if i < 0 {
			fatalf("no check %q for %s", from, platform)
		}
		cs = cs[i:]
	}
	f, err := os.OpenFile(reportPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		fatalf("report: %v", err)
	}
	defer f.Close()
	fmt.Fprintf(f, "\n# bellui %s on %s — %s\n\n| Check | Verdict | Note |\n|---|---|---|\n",
		version, platform, time.Now().Format("2006-01-02 15:04"))

	in := bufio.NewReader(os.Stdin)
	counts := map[string]int{}
	var failed []string
	for i, c := range cs {
		fmt.Printf("\n\033[1m[%d/%d] %s\033[0m\n%s", i+1, len(cs), c.ID, c.text(platform))
		verdict, note := ask(in)
		if verdict == "quit" {
			fmt.Printf("\nStopped. Resume with: go run ./hack/releasecheck run -platform %s -from %s -report %s\n", platform, c.ID, reportPath)
			break
		}
		counts[verdict]++
		if verdict == "FAIL" {
			failed = append(failed, c.ID)
		}
		fmt.Fprintf(f, "| %s %s | %s | %s |\n", c.ID, c.Title, verdict, strings.ReplaceAll(note, "|", "/"))
	}
	summary := fmt.Sprintf("PASS %d, FAIL %d, BLOCKED %d, SKIP %d", counts["PASS"], counts["FAIL"], counts["BLOCKED"], counts["SKIP"])
	fmt.Fprintf(f, "\n%s\n", summary)
	if len(failed) > 0 {
		fmt.Fprintf(f, "\nFailed: %s\n", strings.Join(failed, ", "))
	}
	fmt.Printf("\n%s. Report: %s\n", summary, reportPath)
	if len(failed) > 0 {
		fmt.Printf("Failed: %s — file each with the report's note before tagging.\n", strings.Join(failed, ", "))
		return 1
	}
	return 0
}

// ask reads one verdict. A fail or a blocked check asks for a note, since the
// report is useless without what was seen.
func ask(in *bufio.Reader) (verdict, note string) {
	for {
		fmt.Print("\n[p]ass  [f]ail  [b]locked  [s]kip  [q]uit > ")
		line, err := in.ReadString('\n')
		if err != nil {
			return "quit", ""
		}
		switch strings.ToLower(strings.TrimSpace(line)) {
		case "p":
			fmt.Print("note (optional) > ")
			n, _ := in.ReadString('\n')
			return "PASS", strings.TrimSpace(n)
		case "f", "b":
			v := "FAIL"
			if strings.HasPrefix(strings.ToLower(strings.TrimSpace(line)), "b") {
				v = "BLOCKED"
			}
			for {
				fmt.Print("what did you see? > ")
				n, _ := in.ReadString('\n')
				if n = strings.TrimSpace(n); n != "" {
					return v, n
				}
			}
		case "s":
			fmt.Print("why skipped? > ")
			n, _ := in.ReadString('\n')
			return "SKIP", strings.TrimSpace(n)
		case "q":
			return "quit", ""
		}
	}
}
