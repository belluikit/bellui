#!/usr/bin/env bash
#
# capture.sh — Orca speech-capture harness for the Linux AT-SPI2 backend (pre-rebrand tracker #981).
#
# The busctl/dbus-monitor recipes in hack/a11yprobe verify the *provider* tree
# the way Orca queries it. This harness goes one layer further: it records what
# Orca actually *speaks*, turning the human "does it sound right" listen into a
# diffable transcript — the Linux counterpart of the Windows NVDA speech capture
# (hack/a11yprobe/windows/nvda_speechcapture.ps1).
#
# Mechanism: a speech-dispatcher *generic* output module whose synth command
# appends each utterance's text to a log file instead of (or as well as)
# producing audio. Orca speaks through speech-dispatcher's default module, so
# pointing the default at the logger captures every utterance. No GPU, no audio
# device, and no screen reader are needed to validate the capture itself — a
# plain `spd-say` exercises the exact same path (see `selftest`).
#
# Usage:
#   hack/orcaspeech/capture.sh setup       # install the logging module (idempotent)
#   hack/orcaspeech/capture.sh selftest    # prove capture works via spd-say (no Orca)
#   hack/orcaspeech/capture.sh run         # enable Orca, tail the live transcript
#   hack/orcaspeech/capture.sh run --probe # + launch hack/a11yprobe and walk its focus
#   hack/orcaspeech/capture.sh teardown    # remove the module, restore, disable Orca
#
# The transcript path is $BELLUI_ORCA_SPEECH_LOG (default below).
set -euo pipefail

CFGDIR="${XDG_CONFIG_HOME:-$HOME/.config}/speech-dispatcher"
MODDIR="$CFGDIR/modules"
LOG="${BELLUI_ORCA_SPEECH_LOG:-${XDG_CACHE_HOME:-$HOME/.cache}/bellui-orca-speech/utterances.log}"
SYSCONF="/etc/speech-dispatcher/speechd.conf"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

log() { printf '\033[36m[orcaspeech]\033[0m %s\n' "$*"; }

restart_speechd() {
  systemctl --user restart speech-dispatcher 2>/dev/null \
    || pkill -x speech-dispatcher 2>/dev/null || true
  sleep 1
}

cmd_setup() {
  mkdir -p "$MODDIR" "$(dirname "$LOG")"
  : > "$LOG"

  # Generic module: log $DATA (the utterance) to the transcript. Fast-exits with
  # status 0, which speech-dispatcher treats as "spoken", so Orca keeps flowing.
  # Set BELLUI_ORCA_SPEAK=1 at setup time to ALSO hear it through spd-say's own
  # default (handy for a combined listen + transcript).
  local speak=""
  if [ "${BELLUI_ORCA_SPEAK:-0}" = "1" ]; then
    speak="; spd-say -- \\'\$DATA\\' >/dev/null 2>&1 &"
  fi
  cat > "$MODDIR/bellui-log.conf" <<EOF
# Generated by hack/orcaspeech/capture.sh — a logging synth for pre-rebrand tracker #981.
Debug 0
GenericExecuteSynth "echo \\'\$DATA\\' >> $LOG 2>/dev/null$speak"
GenericLanguage "en" "en-US" "utf-8"
GenericDefaultCharset "utf-8"
AddVoice "en" "MALE1" "default"
EOF

  # User config inherits the full system config, then adds + defaults the logger.
  cat > "$CFGDIR/speechd.conf" <<EOF
# Generated by hack/orcaspeech/capture.sh — remove with \`capture.sh teardown\`.
Include "$SYSCONF"
AddModule "bellui-log" "sd_generic" "bellui-log.conf"
DefaultModule bellui-log
EOF

  restart_speechd
  log "installed logging module; transcript -> $LOG"
}

cmd_selftest() {
  [ -f "$CFGDIR/speechd.conf" ] || cmd_setup
  : > "$LOG"
  spd-say -w "push button, Click me" 2>/dev/null || true
  sleep 1
  if grep -q "push button, Click me" "$LOG"; then
    log "PASS — spd-say utterance captured:"
    sed 's/^/    /' "$LOG"
  else
    log "FAIL — nothing captured. Is speech-dispatcher running? Try: $0 setup"
    return 1
  fi
}

# Drive Orca focus across the a11yprobe widget tree via Component.GrabFocus, so
# the transcript records role+name for each — a deterministic walk. Best-effort:
# depends on the probe being the active window (focus gating), so a manual
# arrow-key navigation with Orca is the fallback.
walk_probe_focus() {
  local a11y name
  a11y=$(busctl --user call org.a11y.Bus /org/a11y/bus org.a11y.Bus GetAddress 2>/dev/null | sed 's/^s "//;s/"$//')
  [ -n "$a11y" ] || return 0
  for n in $(busctl --address "$a11y" call org.a11y.atspi.Registry /org/a11y/atspi/accessible/root org.a11y.atspi.Accessible GetChildren 2>/dev/null | grep -oP ':[0-9.]+' | sort -u); do
    name=$(busctl --address "$a11y" get-property "$n" /org/a11y/atspi/accessible/root org.a11y.atspi.Accessible Name 2>/dev/null)
    echo "$name" | grep -q "Bellui Application" || continue
    # frame 1's widgets live at low object indices; grab each in reading order.
    for p in $(busctl --address "$a11y" call "$n" /org/a11y/atspi/accessible/1 org.a11y.atspi.Accessible GetChildren 2>/dev/null | grep -oP '/org/a11y/atspi/accessible/\d+'); do
      busctl --address "$a11y" call "$n" "$p" org.a11y.atspi.Component GrabFocus >/dev/null 2>&1 || true
      sleep 0.6
    done
    break
  done
}

cmd_run() {
  [ -f "$CFGDIR/speechd.conf" ] || cmd_setup
  : > "$LOG"
  pkill -x orca 2>/dev/null || true; sleep 1

  local probe_pid=""
  if [ "${1:-}" = "--probe" ]; then
    log "building + launching hack/a11yprobe (accessibility tag)…"
    ( cd "$REPO_ROOT" && go build -tags accessibility -o /tmp/orcaspeech-a11yprobe ./hack/a11yprobe )
    /tmp/orcaspeech-a11yprobe >/tmp/orcaspeech-probe.log 2>&1 &
    probe_pid=$!
    sleep 5
  fi

  log "enabling Orca; recording transcript to $LOG (Ctrl-C to stop)"
  gsettings set org.gnome.desktop.a11y.applications screen-reader-enabled true
  trap 'gsettings set org.gnome.desktop.a11y.applications screen-reader-enabled false 2>/dev/null; pkill -x orca 2>/dev/null; [ -n "'"$probe_pid"'" ] && kill '"$probe_pid"' 2>/dev/null; exit 0' INT TERM
  sleep 3

  [ "${1:-}" = "--probe" ] && { log "walking probe focus…"; walk_probe_focus; }

  # Live-tail the transcript until interrupted.
  tail -n +1 -f "$LOG"
}

cmd_teardown() {
  gsettings set org.gnome.desktop.a11y.applications screen-reader-enabled false 2>/dev/null || true
  pkill -x orca 2>/dev/null || true
  rm -f "$CFGDIR/speechd.conf" "$MODDIR/bellui-log.conf"
  restart_speechd
  log "removed logging module; speech restored to the system default"
}

case "${1:-}" in
  setup)    cmd_setup ;;
  selftest) cmd_selftest ;;
  run)      shift; cmd_run "${1:-}" ;;
  teardown) cmd_teardown ;;
  *) echo "usage: $0 {setup|selftest|run [--probe]|teardown}" >&2; exit 2 ;;
esac
