package bellui

import (
	"bytes"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sync"
)

// Resource represents a single binary resource, such as an image or font.
// A resource has an identifying name and byte array content.
// The serialised path of a resource can be obtained which may result in a
// blocking filesystem write operation.
type Resource interface {
	Name() string
	Content() []byte
}

// ThemedResource is a version of a resource that can be updated to match a certain theme color.
// The [ThemeColorName] will be used to look up the color for the current theme and colorize the resource.
//
// Since: 2.5
type ThemedResource interface {
	Resource
	ThemeColorName() ThemeColorName
}

// StreamingResource is a resource that can provide its content as a stream.
// This is useful for large resources where loading everything into memory
// at once is wasteful.
//
// StreamingResource extends [Resource]: the Content() method still works
// (reading all bytes into memory), but Open() provides an [io.ReadCloser]
// for streaming consumption without buffering the entire content.
//
// Since: 2.7
type StreamingResource interface {
	Resource
	Open() (io.ReadCloser, error)
}

// LazyResource is a resource that loads its content on first access.
// After the first call to Content(), the loaded bytes are cached and
// subsequent calls return the cached data with no additional I/O.
//
// If the loader function returns an error, Content() returns nil and
// the error is logged. The next call to Content() will retry the load.
//
// Use [Release] to free cached bytes under memory pressure; the next
// Content() call will re-load them.
//
// LazyResource is safe for concurrent use.
//
// Since: 2.7
type LazyResource struct {
	name   string
	loader func() ([]byte, error)
	opener func() (io.ReadCloser, error) // nil if streaming not supported

	mu     sync.Mutex
	data   []byte
	loaded bool
}

// Name returns the identifying name of this resource.
func (r *LazyResource) Name() string {
	return r.name
}

// Content returns the bytes of the resource, loading them on first call.
// The loaded bytes are cached for subsequent calls. If loading fails,
// the error is logged and nil is returned; the next call will retry.
func (r *LazyResource) Content() []byte {
	r.mu.Lock()
	defer r.mu.Unlock()

	if r.loaded {
		return r.data
	}

	data, err := r.loader()
	if err != nil {
		LogError("Failed to load lazy resource "+r.name, err)
		return nil
	}

	r.data = data
	r.loaded = true
	return r.data
}

// Open returns a reader for the resource content. If the resource was
// created with a path or URI that supports streaming, this returns a
// fresh reader directly from the source without caching all bytes in
// memory. Otherwise it falls back to wrapping Content() in a reader.
func (r *LazyResource) Open() (io.ReadCloser, error) {
	if r.opener != nil {
		return r.opener()
	}
	return io.NopCloser(bytes.NewReader(r.Content())), nil
}

// Loaded reports whether the resource content is currently cached in memory.
func (r *LazyResource) Loaded() bool {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.loaded
}

// Release frees the cached resource content. The next call to Content()
// will re-load the data from the source.
func (r *LazyResource) Release() {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.data = nil
	r.loaded = false
}

// NewLazyResource creates a resource that loads its content on first access
// using the provided loader function. The loader will be called at most once
// unless [LazyResource.Release] is called.
//
// Since: 2.7
func NewLazyResource(name string, loader func() ([]byte, error)) *LazyResource {
	return &LazyResource{
		name:   name,
		loader: loader,
	}
}

// NewStreamingLazyResource creates a resource that loads its content on first
// access using the provided loader function, and supports streaming via
// [StreamingResource.Open] using the provided opener function.
//
// Since: 2.7
func NewStreamingLazyResource(name string, loader func() ([]byte, error), opener func() (io.ReadCloser, error)) *LazyResource {
	return &LazyResource{
		name:   name,
		loader: loader,
		opener: opener,
	}
}

// NewLazyResourceFromPath creates a resource that loads its content from a
// filesystem path on first access. It also supports streaming via [StreamingResource.Open],
// which opens the file directly without caching the bytes.
//
// Since: 2.7
func NewLazyResourceFromPath(path string) *LazyResource {
	cleanPath := filepath.Clean(path)
	return &LazyResource{
		name: filepath.Base(cleanPath),
		loader: func() ([]byte, error) {
			return os.ReadFile(cleanPath)
		},
		opener: func() (io.ReadCloser, error) {
			return os.Open(cleanPath)
		},
	}
}

// StaticResource is a bundled resource compiled into the application.
// These resources are normally generated by the bellui_bundle command included in
// the Bellui toolkit.
type StaticResource struct {
	StaticName    string
	StaticContent []byte
}

// Name returns the unique name of this resource, usually matching the file it
// was generated from.
func (r *StaticResource) Name() string {
	return r.StaticName
}

// Content returns the bytes of the bundled resource, no compression is applied
// but any compression on the resource is retained.
func (r *StaticResource) Content() []byte {
	return r.StaticContent
}

// NewStaticResource returns a new static resource object with the specified
// name and content. Creating a new static resource in memory results in
// sharable binary data that may be serialised to the system cache location.
func NewStaticResource(name string, content []byte) *StaticResource {
	return &StaticResource{
		StaticName:    name,
		StaticContent: content,
	}
}

// LoadResourceFromPath creates a new [StaticResource] in memory using the contents of the specified file.
func LoadResourceFromPath(path string) (Resource, error) {
	bytes, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return nil, err
	}

	name := filepath.Base(path)
	return NewStaticResource(name, bytes), nil
}

// LoadResourceFromURLString creates a new [StaticResource] in memory using the body of the specified URL.
func LoadResourceFromURLString(urlStr string) (Resource, error) {
	res, err := http.Get(urlStr)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()

	bytes, err := io.ReadAll(res.Body)
	if err != nil {
		return nil, err
	}

	name := filepath.Base(urlStr)
	return NewStaticResource(name, bytes), nil
}
